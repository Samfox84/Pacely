import SwiftUI

/// Pacely Calm icons. Shows a calm line icon for an item's emoji when there is one,
/// otherwise the emoji itself. Icons are template images, so they take the foreground colour.
struct PacelyIcon: View {
    let emoji: String
    var size: CGFloat = 22

    var body: some View {
        if let name = PacelyIcon.name(for: emoji) {
            Image("pi-" + name).resizable().renderingMode(.template).scaledToFit()
                .frame(width: size, height: size).accessibilityHidden(true)
        } else {
            Text(emoji).font(.system(size: size * 0.9)).accessibilityHidden(true)
        }
    }

    static func name(for emoji: String) -> String? {
        map[emoji] ?? map[emoji.replacingOccurrences(of: "\u{FE0F}", with: "")]
